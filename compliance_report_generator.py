"""
compliance_report_generator.py — Stage 4: produce the compliance report (JSON + PDF).

Input : a "case bundle" — case metadata, extraction, screening, risk
        assessment and audit trail (from DatabaseHandler.get_case_bundle)
Output: dict { report (full JSON), json_path, pdf_path, report_sha256 }

The report is the artefact an analyst, MLRO or SAMA examiner looks at. It
contains:
* a single, unambiguous DECISION (auto-approve / approve with CDD /
  refer to analyst / block & escalate)
* customer summary (ID number masked — data minimisation)
* sanctions screening result with every candidate and score adjustment
* risk factors, reasoning and recommended actions
* the full hash-chained AUDIT TRAIL and integrity hashes (document SHA-256,
  report SHA-256, audit-chain verification) so the report itself is
  tamper-evident.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import config
from database_handler import canonical_json, sha256_text

logger = config.get_logger("report_generator")
GENERATOR_VERSION = "1.0.0"

DECISIONS = {
    "BLOCK": ("BLOCKED - ESCALATE TO MLRO", "#B42318"),
    "REFER": ("REFER TO COMPLIANCE ANALYST", "#B54708"),
    "APPROVE_CDD": ("APPROVE - STANDARD CDD", "#175CD3"),
    "AUTO_APPROVE": ("AUTO-APPROVE (STRAIGHT-THROUGH)", "#067647"),
}


def decide(screening: dict | None, risk: dict | None) -> str:
    """Map stage results to one decision code."""
    if not screening or not risk:
        return "REFER"
    if screening.get("status") == "MATCH":
        return "BLOCK"
    if risk.get("requires_manual_review") or risk.get("risk_level") == "High":
        return "REFER"
    if risk.get("risk_level") == "Medium":
        return "APPROVE_CDD"
    return "AUTO_APPROVE"


def mask(value: str | None, keep: int = 4) -> str | None:
    if not value:
        return value
    return "*" * max(0, len(value) - keep) + value[-keep:]


def build_report(bundle: dict, audit_chain: dict | None = None) -> dict:
    case, ext, scr, risk = bundle["case"], bundle.get("extraction"), bundle.get("screening"), bundle.get("risk")
    data = (ext or {}).get("data", {})
    meta = (ext or {}).get("metadata", {})
    code = decide(scr, risk)

    report: dict[str, Any] = {
        "report_id": f"RPT-{case['case_id']}",
        "case_id": case["case_id"],
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "generator_version": GENERATOR_VERSION,
        "decision": {"code": code, "label": DECISIONS[code][0]},
        "customer": {
            "full_name": data.get("full_name"),
            "full_name_arabic": data.get("full_name_arabic"),
            "id_type": data.get("id_type"),
            "id_number_masked": mask(data.get("id_number")),
            "nationality": data.get("nationality"),
            "date_of_birth": data.get("date_of_birth"),
            "id_expiry_date": data.get("id_expiry_date"),
            "occupation": data.get("occupation"),
            "employer": data.get("employer"),
            "business_type": data.get("business_type"),
            "city": data.get("city"),
            "monthly_income_sar": data.get("monthly_income_sar"),
            "expected_monthly_volume_sar": data.get("expected_monthly_volume_sar"),
            "source_of_funds": data.get("source_of_funds"),
            "pep_status": data.get("pep_status"),
        },
        "extraction": {
            "method": meta.get("method"), "model": meta.get("model"),
            "confidence": meta.get("confidence"), "missing_fields": meta.get("missing_fields", []),
            "validation_issues": meta.get("validation_issues", []),
            "extraction_notes": meta.get("extraction_notes"),
        },
        "sanctions_screening": scr,
        "risk_assessment": risk,
        "audit_trail": bundle.get("audit_trail", []),
        "integrity": {
            "document_filename": case.get("document_filename"),
            "document_sha256": case.get("document_sha256"),
            "audit_chain": audit_chain,
        },
        "disclaimer": ("Generated by an automated proof-of-concept system using MOCK sanctions data. "
                       "Not for use in real compliance decisions."),
    }
    report["integrity"]["report_sha256"] = sha256_text(canonical_json(
        {k: v for k, v in report.items() if k != "integrity"}))
    return report


def generate_report(bundle: dict, output_dir: str | Path | None = None,
                    audit_chain: dict | None = None, make_pdf: bool = True) -> dict:
    """Build the report and write JSON (+ PDF). Main entry point."""
    out = Path(output_dir or config.REPORTS_DIR)
    out.mkdir(parents=True, exist_ok=True)
    report = build_report(bundle, audit_chain)
    case_id = report["case_id"]

    json_path = out / f"{case_id}.json"
    json_path.write_text(json.dumps(report, indent=2, ensure_ascii=False, default=str), encoding="utf-8")

    pdf_path = None
    if make_pdf:
        try:
            pdf_path = out / f"{case_id}.pdf"
            render_pdf(report, pdf_path)
        except Exception as exc:  # PDF is a convenience; JSON is the system of record
            logger.error("PDF rendering failed for %s: %s", case_id, exc)
            pdf_path = None
    logger.info("Report written: %s%s", json_path.name, f", {pdf_path.name}" if pdf_path else "")
    return {"report": report, "json_path": _rel(json_path),
            "pdf_path": _rel(pdf_path) if pdf_path else None,
            "report_sha256": report["integrity"]["report_sha256"]}


def _rel(p: Path) -> str:
    """Store paths relative to the project so reports/DB rows are portable."""
    try:
        return str(Path(p).resolve().relative_to(config.BASE_DIR))
    except ValueError:
        return str(p)


# --------------------------------------------------------------------------- #
# PDF rendering (reportlab)
# --------------------------------------------------------------------------- #
def render_pdf(report: dict, path: str | Path) -> None:
    from reportlab.lib import colors
    from reportlab.lib.enums import TA_CENTER
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import (KeepTogether, Paragraph, SimpleDocTemplate, Spacer,
                                    Table, TableStyle)

    ss = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=ss["Title"], fontSize=17, spaceAfter=2)
    h2 = ParagraphStyle("h2", parent=ss["Heading2"], fontSize=12, spaceBefore=10, spaceAfter=4,
                        textColor=colors.HexColor("#101828"))
    body = ParagraphStyle("b", parent=ss["BodyText"], fontSize=9, leading=12)
    small = ParagraphStyle("s", parent=body, fontSize=7.5, leading=9.5, textColor=colors.HexColor("#475467"))
    cell = ParagraphStyle("c", parent=body, fontSize=8, leading=10)
    banner_style = ParagraphStyle("banner", parent=body, fontSize=13, leading=16,
                                  textColor=colors.white, alignment=TA_CENTER)

    def P(text: Any, style=cell) -> Paragraph:
        s = "" if text is None else str(text)
        return Paragraph(s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"), style)

    def kv_table(rows: list[tuple[str, Any]]) -> Table:
        t = Table([[P(k, small), P(v)] for k, v in rows], colWidths=[45 * mm, 125 * mm])
        t.setStyle(TableStyle([
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("LINEBELOW", (0, 0), (-1, -1), 0.25, colors.HexColor("#EAECF0")),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 3), ("TOPPADDING", (0, 0), (-1, -1), 3)]))
        return t

    def grid(header: list[str], rows: list[list[Any]], widths: list[float]) -> Table:
        t = Table([[P(h, small) for h in header]] + [[P(c) for c in r] for r in rows],
                  colWidths=[w * mm for w in widths], repeatRows=1)
        t.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#F2F4F7")),
            ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#D0D5DD")),
            ("VALIGN", (0, 0), (-1, -1), "TOP")]))
        return t

    code = report["decision"]["code"]
    label, color = DECISIONS[code]
    c, risk, scr = report["customer"], report.get("risk_assessment") or {}, report.get("sanctions_screening") or {}

    story: list[Any] = [
        Paragraph("KYC / AML Compliance Report", h1),
        P(f"Case {report['case_id']}  |  Report {report['report_id']}  |  Generated {report['generated_at']} UTC", small),
        Spacer(1, 6),
    ]
    banner = Table([[Paragraph(f"<b>{label}</b><br/><font size=9>Risk level: {risk.get('risk_level', 'n/a')} "
                               f"(score {risk.get('risk_score', 'n/a')}/100)  |  Sanctions: {scr.get('status', 'n/a')}  "
                               f"|  Due diligence: {risk.get('due_diligence', 'n/a')}</font>", banner_style)]],
                   colWidths=[170 * mm])
    banner.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), colors.HexColor(color)),
                                ("TOPPADDING", (0, 0), (-1, -1), 8), ("BOTTOMPADDING", (0, 0), (-1, -1), 8)]))
    story += [banner, Paragraph("1. Customer", h2), kv_table([
        ("Full name", c["full_name"]), ("Name (Arabic)", c["full_name_arabic"]),
        ("ID", f"{c['id_type'] or ''} {c['id_number_masked'] or ''}"),
        ("Nationality", c["nationality"]), ("Date of birth", c["date_of_birth"]),
        ("ID expiry", c["id_expiry_date"]), ("Occupation", c["occupation"]),
        ("Employer / business", " / ".join(filter(None, [c["employer"], c["business_type"]]))),
        ("Monthly income (SAR)", f"{c['monthly_income_sar']:,.0f}" if c["monthly_income_sar"] else None),
        ("Expected monthly volume (SAR)",
         f"{c['expected_monthly_volume_sar']:,.0f}" if c["expected_monthly_volume_sar"] else None),
        ("Source of funds", c["source_of_funds"]), ("PEP", "Yes" if c["pep_status"] else "No"),
    ])]

    ex = report["extraction"]
    story += [Paragraph("2. Document extraction", h2), kv_table([
        ("Method", f"{ex['method']}{' (' + ex['model'] + ')' if ex.get('model') else ''}"),
        ("Confidence", ex["confidence"]),
        ("Missing fields", ", ".join(ex["missing_fields"]) or "None"),
        ("Validation issues", "; ".join(ex["validation_issues"]) or "None"),
        ("Extractor notes", ex.get("extraction_notes") or "None"),
    ])]

    story += [Paragraph("3. Sanctions screening", h2), kv_table([
        ("Result", f"{scr.get('status')} (top score {scr.get('top_score')})"),
        ("Lists checked", f"{', '.join(scr.get('lists_checked', []))} - version {scr.get('list_version')}"),
        ("Explanation", scr.get("explanation")),
    ])]
    if scr.get("matches"):
        story += [Spacer(1, 4), grid(
            ["List / UID", "Listed name", "Matched on", "Name", "Final", "Adjustments", "Decision"],
            [[f"{m['list']} {m['uid']}", m["listed_name"], f"{m['matched_name']} ({m['matched_on']})",
              f"{m['name_score']:.2f}", f"{m['final_score']:.2f}", "; ".join(m["adjustments"]) or "-",
              m["decision"]] for m in scr["matches"]],
            [25, 25, 28, 13, 13, 42, 24])]

    story += [Paragraph("4. Risk assessment", h2), kv_table([
        ("Final level", f"{risk.get('risk_level')} (rules: {risk.get('rule_based_level')}, "
                        f"AI: {risk.get('ai_level') or 'n/a'})"),
        ("Method", f"{risk.get('method')}{' (' + risk['model'] + ')' if risk.get('model') else ''}"),
        ("Reasoning", risk.get("reasoning")),
        ("Manual review", "Required: " + "; ".join(risk.get("review_reasons", []))
         if risk.get("requires_manual_review") else "Not required"),
        ("Next KYC review", risk.get("next_review_date")),
    ])]
    if risk.get("factors"):
        story += [Spacer(1, 4), grid(["Category", "Factor", "Points", "Detail"],
                                     [[f["category"], f["factor"], f["points"], f["detail"]] for f in risk["factors"]],
                                     [24, 52, 14, 80])]
    if risk.get("recommended_actions"):
        story += [Paragraph("Recommended actions", ParagraphStyle("h3", parent=h2, fontSize=10)),
                  *[P(f"- {a}", body) for a in risk["recommended_actions"]]]

    trail = report.get("audit_trail", [])
    story += [Paragraph("5. Audit trail", h2), grid(
        ["#", "Timestamp (UTC)", "Actor", "Action", "Entry hash"],
        [[e["id"], e["timestamp"], e["actor"], e["action"], e["entry_hash"][:16] + "..."] for e in trail],
        [10, 38, 40, 42, 40])]

    integ = report["integrity"]
    chain = integ.get("audit_chain") or {}
    story += [KeepTogether([Paragraph("6. Integrity", h2), kv_table([
        ("Document", integ.get("document_filename")),
        ("Document SHA-256", integ.get("document_sha256")),
        ("Report SHA-256", integ.get("report_sha256")),
        ("Audit chain", f"{'VALID' if chain.get('valid') else 'INVALID'} ({chain.get('entries')} entries)"
         if chain else "not verified"),
    ])]), Spacer(1, 8), P(report["disclaimer"], small)]

    doc = SimpleDocTemplate(str(path), pagesize=A4, leftMargin=20 * mm, rightMargin=20 * mm,
                            topMargin=16 * mm, bottomMargin=16 * mm,
                            title=f"KYC/AML Report {report['case_id']}", author="KYC/AML Automation PoC")
    doc.build(story)


if __name__ == "__main__":
    import argparse
    from database_handler import DatabaseHandler
    p = argparse.ArgumentParser(description="(Re)generate the report for a stored case")
    p.add_argument("case_id")
    a = p.parse_args()
    db = DatabaseHandler()
    res = generate_report(db.get_case_bundle(a.case_id), audit_chain=db.verify_audit_chain())
    print(json.dumps({k: v for k, v in res.items() if k != "report"}, indent=2))
